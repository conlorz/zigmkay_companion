//! Explicit real compiler/cache archive fixture. No downloads, clones or devices.
const std = @import("std");
const jobs = @import("companion-jobs");
test "real offline import verifies reuse and preserves a corrupted owned cache tree" {
    const t = std.testing;
    const options = @import("options");
    const receipt_bytes = try std.Io.Dir.cwd().readFileAlloc(t.io, options.receipt, t.allocator, .limited(32 * 1024));
    defer t.allocator.free(receipt_bytes);
    const compiler = try jobs.toolchain.Receipt.parse(t.allocator, receipt_bytes);
    defer compiler.deinit(t.allocator);
    var environment = std.process.Environ.Map.init(t.allocator);
    defer environment.deinit();
    var tmp = t.tmpDir(.{ .iterate = true });
    defer tmp.cleanup();
    const input = jobs.package_cache.Input{ .offline_archive = options.archive };
    var first = try jobs.package_cache.acquire(t.allocator, t.io, &environment, compiler, tmp.dir, options.package_hash, input);
    defer first.deinit();
    const cache_path = try tmp.dir.realPathFileAlloc(t.io, ".", t.allocator);
    defer t.allocator.free(cache_path);
    try first.source.verify(t.allocator, t.io, cache_path);
    var loaded = (try jobs.package_cache.load(t.allocator, t.io, tmp.dir, options.package_hash)) orelse return error.MissingVerifiedSourceRecord;
    defer loaded.deinit();
    try t.expectEqual(first.source.tree_digest, loaded.source.tree_digest);
    var second = try jobs.package_cache.acquire(t.allocator, t.io, &environment, compiler, tmp.dir, options.package_hash, input);
    defer second.deinit();
    try t.expectEqual(first.source.tree_digest, second.source.tree_digest);
    var relocated_cache = t.tmpDir(.{ .iterate = true });
    defer relocated_cache.cleanup();
    var relocated = try jobs.package_cache.acquire(t.allocator, t.io, &environment, compiler, relocated_cache.dir, options.package_hash, .{ .offline_archive = first.source.archive_path });
    defer relocated.deinit();
    try t.expectEqual(first.source.tree_digest, relocated.source.tree_digest);
    var source = try std.Io.Dir.cwd().openDir(t.io, first.source.source_path, .{});
    defer source.close(t.io);
    const changed = "// explicit generated cache corruption fixture\n";
    try source.writeFile(t.io, .{ .sub_path = "build.zig", .data = changed });
    try t.expectError(error.CachedPackageSourceChanged, first.source.verify(t.allocator, t.io, cache_path));
    try t.expectError(error.CachedPackageSourceChanged, jobs.package_cache.load(t.allocator, t.io, tmp.dir, options.package_hash));
    try t.expectError(error.CachedPackageSourceChanged, jobs.package_cache.acquire(t.allocator, t.io, &environment, compiler, tmp.dir, options.package_hash, input));
    const retained = try source.readFileAlloc(t.io, "build.zig", t.allocator, .limited(4096));
    defer t.allocator.free(retained);
    try t.expectEqualStrings(changed, retained);
    const blob = try std.Io.Dir.cwd().readFileAlloc(t.io, first.source.archive_path, t.allocator, .limited(512 * 1024 * 1024));
    defer t.allocator.free(blob);
    try t.expectEqual(first.source.archive_digest, jobs.firmware.digest(blob));
}
